"""Record installed versions for the current Python/Linux dependency closure.

Run deliberately after reviewed dependency changes; this is not an advisory scan.
"""
from importlib.metadata import distribution
from pathlib import Path
import tomllib

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

root = Path(__file__).resolve().parents[1]
project = tomllib.loads((root/'pyproject.toml').read_text())
roots = project['project']['dependencies'] + project['build-system']['requires'] + project['project']['optional-dependencies']['dev']
queue = []
for raw in roots:
    requirement = Requirement(raw)
    queue.append((requirement.name, ''))
    queue.extend((requirement.name, extra) for extra in requirement.extras)
seen, visited = {}, set()
while queue:
    name, extra = queue.pop()
    key = (canonicalize_name(name), extra)
    if key in visited:
        continue
    visited.add(key)
    installed = distribution(name)
    seen[canonicalize_name(name)] = (installed.metadata['Name'], installed.version)
    for raw in installed.requires or []:
        requirement = Requirement(raw)
        if requirement.marker is None or requirement.marker.evaluate({'extra':extra}):
            queue.append((requirement.name,''))
            queue.extend((requirement.name,value) for value in requirement.extras)
(root/'requirements.lock').write_text(
    '# Python 3.12 Linux dependency closure; generated by scripts/lock_dependencies.py.\n'
    + '\n'.join(f'{name}=={version}' for _,(name,version) in sorted(seen.items())) + '\n')
print(f'Locked {len(seen)} installed distribution versions.')
